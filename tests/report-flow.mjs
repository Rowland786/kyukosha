// 新版提交页走一遍并截图：ID → 视频 → 确认 → 回执
import { chromium } from 'playwright-core';
import { writeFileSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import path from 'node:path';
import os from 'node:os';
const SITE = (process.env.SITE || 'http://localhost:5178/kyukosha').replace(/\/$/, '');
const OUT = process.env.SHOTS || os.tmpdir();
const W = +(process.env.W || 1440), H = +(process.env.H || 900);
const vid = path.join(os.tmpdir(), 'kyukosha-flow.mp4');
writeFileSync(vid, randomBytes(1.2 * 1024 * 1024));
const b = await chromium.launch({ channel: 'msedge', headless: true });
const m = W < 600;
const p = await (await b.newContext({ viewport: { width: W, height: H }, isMobile: m, hasTouch: m, deviceScaleFactor: m ? 2 : 1 })).newPage();
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
await p.goto(SITE + '/report/', { waitUntil: 'networkidle' });
await p.waitForTimeout(2500);
await p.screenshot({ path: path.join(OUT, `rp-${W}-0.png`) });
await p.click('[data-step="0"] [data-go="1"]');
await p.fill('#target', process.env.TARGET || '156');
await p.click('#lookupBtn');
await p.waitForSelector('#idNext:not([hidden])', { timeout: 20000 });
await p.waitForTimeout(800);
await p.screenshot({ path: path.join(OUT, `rp-${W}-1.png`) });
await p.click('#idNext [data-go="2"]');
await p.setInputFiles('#fileInput', vid);
await p.waitForSelector('.file.done', { timeout: 60000 });
await p.check('#notObs', { force: true });
await p.waitForSelector('#videoNext:not([hidden])');
await p.waitForTimeout(600);
await p.screenshot({ path: path.join(OUT, `rp-${W}-2.png`) });
await p.click('#videoNext [data-go="3"]');
await p.fill('#note', '【测试】视频 00:10 开始。');
await p.check('#consent', { force: true });
await p.waitForTimeout(700);
await p.screenshot({ path: path.join(OUT, `rp-${W}-3.png`) });
await p.click('#submit');
await p.waitForSelector('#receipt:not([hidden])', { timeout: 30000 });
await p.waitForTimeout(1200);
await p.screenshot({ path: path.join(OUT, `rp-${W}-4.png`) });
console.log('case', await p.textContent('#rcId'), 'errors', errs.length, errs.join(' | '));
await b.close();
